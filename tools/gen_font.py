#!/usr/bin/env python3
"""生成 5x7 ASCII 点阵字体头文件 (epd_font_5x7.h)，并输出预览图用于人工校验。

字体数据来自 tools/font5x7_ascii.py，该文件由 Adafruit-GFX 的
glcdfont.c 提取（BSD-2-Clause），是真正的 5x7 点阵，而不是把 TTF
缩小到 5x7 后阈值化（那种做法会丢掉细笔画）。

位序约定：每个字模 5 个字节，每字节代表一列（列序从左到右），
          每字节内 bit0 = 最上一行，bit6 = 基线行，bit7 = 下伸行。

用法：
    python tools/gen_font.py
"""
import os

from PIL import Image, ImageDraw

from font5x7_ascii import GLYPHS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_H = os.path.normpath(os.path.join(
    HERE, "..", "components", "epd_ssd1619a", "epd_font_5x7.h"))
PREVIEW = os.path.normpath(os.path.join(HERE, "..", "docs", "font_preview.png"))

FIRST, LAST = 0x20, 0x7E
# The classic 5x7 font uses rows 0..6 for the glyph body; some glyphs
# (comma, semicolon, g, j, p, q, y) use bit7 for the descender.
W, H = 5, 8


def check_glyphs():
    if len(GLYPHS) != LAST - FIRST + 1:
        raise SystemExit("GLYPHS must contain %d entries" % (LAST - FIRST + 1))
    for code, glyph in zip(range(FIRST, LAST + 1), GLYPHS):
        if len(glyph) != W:
            raise SystemExit("glyph %r has %d columns, expected %d"
                             % (chr(code), len(glyph), W))
        for col in glyph:
            if col & ~0xFF:
                raise SystemExit("glyph %r has bits outside 8 rows" % chr(code))
        if code != 0x20 and not any(glyph):
            raise SystemExit("glyph %r is empty" % chr(code))


def write_header():
    out = [
        "/* Auto-generated by tools/gen_font.py - do not edit.",
        " * 5x7 ASCII font: 5 columns per glyph, column-major,",
        " * bit0 = top row, bit6 = baseline row, bit7 = descender row.",
        " * columns left->right.",
        " *",
        " * Glyph data derived from Adafruit-GFX-Library glcdfont.c,",
        " * Copyright (c) 2012 Adafruit Industries. BSD-2-Clause license.",
        " * https://github.com/adafruit/Adafruit-GFX-Library",
        " *",
        " * SPDX-License-Identifier: BSD-2-Clause",
        " */",
        "#ifndef EPD_FONT_5X7_HEADER_H",
        "#define EPD_FONT_5X7_HEADER_H",
        "",
        "#include <stdint.h>",
        "",
        "#define EPD_FONT_FIRST %d" % FIRST,
        "#define EPD_FONT_LAST  %d" % LAST,
        "#define EPD_FONT_W     %d" % W,
        "#define EPD_FONT_HEIGHT %d" % H,
        "",
        "static const uint8_t font5x7[%d][%d] = {" % (len(GLYPHS), W),
    ]

    for code, glyph in zip(range(FIRST, LAST + 1), GLYPHS):
        ch = chr(code)
        if ch == "'":
            label = "\\'"
        elif ch == "\\":
            label = "\\\\"
        else:
            label = ch
        out.append("    { 0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X }, /* '%s' */"
                   % (glyph[0], glyph[1], glyph[2], glyph[3], glyph[4], label))

    out += ["};", "", "#endif", ""]
    with open(OUT_H, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out))


def write_preview():
    cols, cell, scale = 16, 8, 4
    rows = (len(GLYPHS) + cols - 1) // cols
    img = Image.new("1", (cols * cell * scale, rows * cell * scale), 0)
    draw = ImageDraw.Draw(img)
    for i, glyph in enumerate(GLYPHS):
        ox = (i % cols) * cell * scale
        oy = (i // cols) * cell * scale
        for x in range(W):
            for y in range(H):
                if (glyph[x] >> y) & 1:
                    px = ox + (x + 1) * scale
                    py = oy + (y + 1) * scale
                    draw.rectangle([px - scale, py - scale, px - 1, py - 1], fill=1)
    img.save(PREVIEW)


def main():
    check_glyphs()
    write_header()
    write_preview()
    print("wrote", OUT_H)
    print("wrote", PREVIEW)


if __name__ == "__main__":
    main()
